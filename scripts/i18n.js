'use strict';
/**
 * Shared translation build + validation helpers.
 *
 * translations.json is the source of truth (edit it only through translate.js,
 * or by hand if you know what you are doing). This module turns it into one
 * lazy-loaded file per language plus a small index, and validates the result.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const DECK_FILE = path.join(ROOT, 'cards.js');
const STORE_FILE = path.join(ROOT, 'translations.json');
const LANGS_FILE = path.join(ROOT, 'languages.json');
const OUT_DIR = path.join(ROOT, 'translations');
const INDEX_FILE = path.join(ROOT, 'translations.js');

const FIELDS = ['kicker', 'title', 'claim', 'body'];

function loadDeck() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(DECK_FILE, 'utf8'), sandbox);
  if (!sandbox.window.DECK) throw new Error('cards.js must define window.DECK');
  return sandbox.window.DECK;
}

function readStore() {
  return fs.existsSync(STORE_FILE) ? JSON.parse(fs.readFileSync(STORE_FILE, 'utf8')) : {};
}

function readLanguages() {
  return JSON.parse(fs.readFileSync(LANGS_FILE, 'utf8'));
}

const sha = (value) => crypto.createHash('sha1').update(JSON.stringify(value)).digest('hex').slice(0, 12);
const cardHash = (card) => sha(FIELDS.map((field) => card[field]));
const uiHash = (ui) => sha(Object.keys(ui).sort().map((key) => ui[key]));

const normDigits = (text) => text.replace(/\p{Nd}/gu, (digit) => {
  const cp = digit.codePointAt(0);
  if (cp >= 0x0660 && cp <= 0x0669) return String.fromCharCode(cp - 0x0660 + 48);
  if (cp >= 0x06F0 && cp <= 0x06F9) return String.fromCharCode(cp - 0x06F0 + 48);
  if (cp >= 0x0966 && cp <= 0x096F) return String.fromCharCode(cp - 0x0966 + 48);
  if (cp >= 0x09E6 && cp <= 0x09EF) return String.fromCharCode(cp - 0x09E6 + 48);
  if (cp >= 0x0E50 && cp <= 0x0E59) return String.fromCharCode(cp - 0x0E50 + 48);
  return digit;
});

const tagSig = (html) => (html.match(/<[^>]+>/g) || [])
  .map((tag) => tag.replace(/"/g, "'").replace(/\s+/g, ' ').trim())
  .join('|');

const digitSig = (html) => (normDigits(html.replace(/<[^>]+>/g, ' ')).match(/\d+/g) || []).sort().join(',');

const stripTags = (html) => html.replace(/<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/gi, ' ').replace(/\s+/g, ' ').trim();

function atomicWrite(file, text) {
  const temporary = file + '.tmp';
  fs.writeFileSync(temporary, text, 'utf8');
  fs.renameSync(temporary, file);
}

function safeJson(value) {
  return JSON.stringify(value).replace(/<\/script/gi, '<\\/script');
}

/** Build translations/<code>.js and the translations.js index. */
function buildTranslations(options = {}) {
  const deck = loadDeck();
  const store = readStore();
  const languages = readLanguages();
  const outDir = options.outDir || OUT_DIR;

  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  const codes = Object.keys(store).filter((code) => store[code] && /^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$/.test(code));
  const order = Object.keys(languages);
  codes.sort((a, b) => {
    const ai = order.indexOf(a), bi = order.indexOf(b);
    return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi) || a.localeCompare(b);
  });

  const index = [];
  const summary = [];

  for (const code of codes) {
    const source = store[code];
    const cards = {};
    for (const card of deck.cards) {
      const translated = source.cards && source.cards[card.slug];
      if (!translated) continue;
      const clean = {};
      for (const field of FIELDS) {
        if (typeof translated[field] === 'string' && translated[field].trim()) clean[field] = translated[field];
      }
      if (Object.keys(clean).length) cards[card.slug] = clean;
    }

    const data = { cards };
    if (source.ui) {
      const ui = {};
      for (const key of Object.keys(deck.ui)) {
        if (typeof source.ui[key] === 'string' && source.ui[key].trim()) ui[key] = source.ui[key];
      }
      if (Object.keys(ui).length) data.ui = ui;
    }

    const complete = deck.cards.filter((card) => {
      const translated = cards[card.slug];
      return translated && FIELDS.every((field) => typeof translated[field] === 'string' && translated[field].trim());
    }).length;

    const body = '// Generated by scripts/build-translations.js. Do not edit by hand.\n'
      + 'window.TRANSLATIONS = window.TRANSLATIONS || {};\n'
      + 'window.TRANSLATIONS[' + JSON.stringify(code) + '] = ' + safeJson(data) + ';\n';
    atomicWrite(path.join(outDir, code + '.js'), body);

    const meta = languages[code] || {};
    index.push({
      code,
      native: meta.native || code,
      english: meta.english || code,
      dir: meta.dir || 'ltr',
      cards: complete,
      total: deck.cards.length
    });
    summary.push({ code, cards: complete, total: deck.cards.length, bytes: Buffer.byteLength(body) });
  }

  const indexBody = '// Generated by scripts/build-translations.js. Do not edit by hand.\n'
    + 'window.TRANSLATION_LANGS = ' + safeJson(index) + ';\n';
  atomicWrite(INDEX_FILE, indexBody);

  return { summary, index };
}

const ARABIC = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]/g;
const LETTER = /\p{L}/gu;

function scriptRatio(text, pattern) {
  const letters = (text.match(LETTER) || []).length;
  if (!letters) return 0;
  const matches = (text.match(pattern) || []).length;
  return matches / letters;
}

/** Validate every translation against the English source. Returns { errors, warnings }. */
function validateTranslations(options = {}) {
  const deck = loadDeck();
  const store = readStore();
  const languages = readLanguages();
  const errors = [];
  const warnings = [];
  const codes = Object.keys(store).filter((code) => store[code]);

  for (const code of codes) {
    const source = store[code];
    const meta = languages[code] || {};
    const where = (suffix) => code + (suffix ? ' / ' + suffix : '');

    if (!meta.native) warnings.push(where('') + ': no entry in languages.json');

    if (!source.ui) {
      errors.push(where('ui') + ': missing ui block');
    } else {
      for (const key of Object.keys(deck.ui)) {
        const value = source.ui[key];
        if (typeof value !== 'string' || !value.trim()) {
          errors.push(where('ui.' + key) + ': missing or empty');
          continue;
        }
        if (tagSig(deck.ui[key]) !== tagSig(value)) errors.push(where('ui.' + key) + ': HTML tags changed');
        if (value.indexOf('\uFFFD') > -1) errors.push(where('ui.' + key) + ': contains replacement character');
        if (key === 'cardOf') {
          for (const placeholder of ['{n}', '{total}']) {
            if (value.indexOf(placeholder) === -1) errors.push(where('ui.cardOf') + ': missing ' + placeholder);
          }
        }
      }
    }

    for (const card of deck.cards) {
      const translated = source.cards && source.cards[card.slug];
      if (!translated) { errors.push(where(card.slug) + ': missing card'); continue; }
      for (const field of FIELDS) {
        if (typeof translated[field] !== 'string' || !translated[field].trim()) {
          errors.push(where(card.slug + '.' + field) + ': missing or empty');
        }
      }
      if (typeof translated.body !== 'string') continue;
      const body = translated.body;
      if (tagSig(card.body) !== tagSig(body)) errors.push(where(card.slug) + ': HTML tags/attributes changed');
      if (digitSig(card.body) !== digitSig(body)) errors.push(where(card.slug) + ': numbers changed');
      if (body.indexOf('\uFFFD') > -1) errors.push(where(card.slug) + ': contains replacement character');
      if (/<\/script/i.test(body)) errors.push(where(card.slug) + ': contains </script');
      const ratio = body.length / card.body.length;
      if (ratio < 0.55 || ratio > 2.2) warnings.push(where(card.slug) + ': body length ratio ' + ratio.toFixed(2));
      for (const tag of ['details', 'summary']) {
        const expected = (card.body.match(new RegExp('<' + tag + '\\b', 'g')) || []).length;
        const actual = (body.match(new RegExp('<' + tag + '\\b', 'g')) || []).length;
        if (expected !== actual) errors.push(where(card.slug) + ': <' + tag + '> count ' + actual + ', expected ' + expected);
      }
      if (code === 'ar' || code === 'ur' || code === 'fa' || code === 'ps') {
        const arabic = scriptRatio(stripTags(body), ARABIC);
        if (arabic < 0.4) errors.push(where(card.slug) + ': Arabic-script ratio only ' + arabic.toFixed(2));
      }
      if (!translated._src) warnings.push(where(card.slug) + ': no _src hash');
      else if (translated._src !== cardHash(card)) warnings.push(where(card.slug) + ': translation is stale (source changed)');
    }
  }

  return { errors, warnings };
}

module.exports = {
  ROOT,
  FIELDS,
  loadDeck,
  readStore,
  readLanguages,
  cardHash,
  uiHash,
  tagSig,
  digitSig,
  stripTags,
  buildTranslations,
  validateTranslations
};

if (require.main === module) {
  const { summary } = buildTranslations();
  for (const row of summary) console.log(row.code + ': ' + row.cards + '/' + row.total + ' cards, ' + (row.bytes / 1024).toFixed(1) + ' KB');
}
