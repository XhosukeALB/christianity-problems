#!/usr/bin/env node
/**
 * Pre-compiles static translations with the Gemini API.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const DIR = __dirname;
const JSON_FILE = path.join(DIR, 'translations.json');
const JS_FILE = path.join(DIR, 'translations.js');
const CARDS_FILE = path.join(DIR, 'cards.js');
const DEFAULT_MODEL = 'gemini-3.8-flash';
const FIELDS = ['kicker', 'title', 'claim', 'body'];
const UI_FIELDS = ['kicker', 'title', 'sub', 'cover', 'sources', 'hint1', 'hint2', 'hint3', 'hint4'];

function loadDeck() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(CARDS_FILE, 'utf8'), sandbox);
  if (!sandbox.window.DECK) throw new Error('cards.js must define window.DECK');
  return sandbox.window.DECK;
}

const sha = (obj) => crypto.createHash('sha1').update(JSON.stringify(obj)).digest('hex').slice(0, 12);
const cardHash = (c) => sha(FIELDS.map((f) => c[f]));
const uiHash = (ui) => sha(UI_FIELDS.map((f) => ui[f]));

const normDigits = (s) => s.replace(/\p{Nd}/gu, d => {
  const cp = d.codePointAt(0);
  if (cp >= 0x0660 && cp <= 0x0669) return String.fromCharCode(cp - 0x0660 + 48);
  if (cp >= 0x06F0 && cp <= 0x06F9) return String.fromCharCode(cp - 0x06F0 + 48);
  if (cp >= 0x0966 && cp <= 0x096F) return String.fromCharCode(cp - 0x0966 + 48);
  if (cp >= 0x09E6 && cp <= 0x09EF) return String.fromCharCode(cp - 0x09E6 + 48);
  if (cp >= 0x0E50 && cp <= 0x0E59) return String.fromCharCode(cp - 0x0E50 + 48);
  return d;
});

const tagSig = (html) => (html.match(/<[^>]+>/g) || []).map(t => t.replace(/"/g, "'").replace(/\s+/g, ' ').trim()).join('|');
const digitSig = (html) => (normDigits(html.replace(/<[^>]+>/g, ' ')).match(/\d+/g) || []).sort().join(',');

function readStore() {
  return fs.existsSync(JSON_FILE) ? JSON.parse(fs.readFileSync(JSON_FILE, 'utf8')) : {};
}

function atomicWrite(file, text) {
  const tmp = file + '.tmp';
  fs.writeFileSync(tmp, text, 'utf8');
  fs.renameSync(tmp, file);
}

function saveStore(store, deck) {
  atomicWrite(JSON_FILE, JSON.stringify(store, null, 2) + '\n');
  const slugs = deck.cards.map((c) => c.slug);
  const out = {};
  for (const lang of Object.keys(store).sort()) {
    const cards = {};
    for (const slug of slugs) {
      const c = store[lang].cards && store[lang].cards[slug];
      if (!c) continue;
      cards[slug] = {};
      for (const f of FIELDS) if (c[f] != null) cards[slug][f] = c[f];
    }
    out[lang] = { cards };
    if (store[lang].ui) out[lang].ui = store[lang].ui;
  }
  const body = JSON.stringify(out, null, 2).replace(/<\/script/gi, '<\\/script');
  atomicWrite(JS_FILE, '// Generated by translate.js. Do not edit by hand.\nwindow.TRANSLATIONS = ' + body + ';\n');
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function callGemini(systemText, payload, env, fetchImpl) {
  const model = env.GEMINI_MODEL || DEFAULT_MODEL;
  const url = 'https://generativelanguage.googleapis.com/v1beta/models/' + encodeURIComponent(model) + ':generateContent';
  const body = JSON.stringify({
    systemInstruction: { parts: [{ text: systemText }] },
    contents: [{ role: 'user', parts: [{ text: JSON.stringify(payload) }] }],
    generationConfig: { temperature: 0.1, responseMimeType: 'application/json' },
  });
  let lastErr, rateLimited = false;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const res = await fetchImpl(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'x-goog-api-key': env.GEMINI_API_KEY },
        body,
      });
      if (res.ok) {
        const data = await res.json();
        const parts = (data.candidates && data.candidates[0] && data.candidates[0].content && data.candidates[0].content.parts) || [];
        const text = parts.map((p) => p.text || '').join('').trim();
        if (!text) throw new Error('Empty response (possibly blocked by a safety filter)');
        return JSON.parse(text.replace(/^```(?:json)?\s*|\s*```$/g, ''));
      }
      
      const errText = (await res.text()).slice(0, 400);
      if (res.status === 429) {
        rateLimited = true;
        const retryMatch = errText.match(/"retryDelay":\s*"(\d+)s"/) || errText.match(/retry after (\d+)/i);
        const wait = retryMatch ? (parseInt(retryMatch[1]) * 1000 + 1000) : (5000 * attempt);
        console.warn('\n   Rate limited. Waiting ' + (wait/1000) + 's...');
        await sleep(wait);
        throw new Error('HTTP 429: Rate limited');
      }
      if (res.status === 404) throw Object.assign(new Error('HTTP 404: Model not found. ' + errText), { fatal: true });
      if (res.status === 400 || res.status === 401 || res.status === 403) throw Object.assign(new Error('HTTP ' + res.status + ': Check API key. ' + errText), { fatal: true });
      
      throw new Error('HTTP ' + res.status + ': ' + errText);
    } catch (e) {
      lastErr = e;
      if (e.fatal || attempt === 4) break;
      if (rateLimited) rateLimited = false;
      else await sleep(5000 * attempt);
    }
  }
  throw lastErr;
}

const SYSTEM = (lang) => `You are an expert academic translator. Translate the values of the JSON object you receive into the language with code "${lang}".
Rules:
1. Return ONLY a JSON object with exactly the same keys. No markdown, no commentary.
2. Keep every HTML tag and attribute exactly as given, in the same order. Translate only the text between tags.
3. Keep names of people and works as in the source unless the target language has a standard localized form. Keep numbers and years.
4. Render Bible references and book names in the conventional form of the target language.
5. Use the target language's standard quotation marks. Keep the tone academic and neutral.
6. Do not add, remove, soften or strengthen any claim.
7. Glossary constraints:
   - "Evidence Deck" -> ES: "Compendio de pruebas", FR: "Dossier de preuves", DE: "Beweisdossier"
   - "Pressure Points" -> ES: "Objeciones y respuestas", FR: "Objections et réponses"
   - "Triad" -> FR: "triade inconsistante"`;

async function translateObject(lang, obj, fields, check, env, fetchImpl) {
  const payload = {};
  for (const f of fields) payload[f] = obj[f];
  let lastProblem = '';
  for (let attempt = 1; attempt <= 3; attempt++) {
    let systemPrompt = SYSTEM(lang);
    if (lastProblem) systemPrompt += `\n\nYour previous output was rejected: ${lastProblem}. Fix this.`;
    const out = await callGemini(systemPrompt, payload, env, fetchImpl);
    const problem = fields.map((f) => (typeof out[f] === 'string' && out[f].trim() ? '' : 'missing "' + f + '"')).find(Boolean) || check(payload, out);
    if (!problem) {
      const clean = {};
      for (const f of fields) clean[f] = out[f];
      return clean;
    }
    lastProblem = problem;
  }
  throw new Error('Validation failed after 3 tries: ' + lastProblem);
}

const checkCard = (src, out) => {
  if (tagSig(src.body) !== tagSig(out.body)) return 'HTML tags/attributes in body changed';
  if (digitSig(src.body) !== digitSig(out.body)) return 'Numbers in body changed';
  const srcLen = src.body.length;
  const outLen = out.body.length;
  if (outLen < srcLen * 0.5 || outLen > srcLen * 2.5) return 'Body length is anomalous';
  for (const f of ['kicker', 'title', 'claim']) if (/<[a-z]/i.test(out[f]) && !/<[a-z]/i.test(src[f])) return 'tags appeared in ' + f;
  return '';
};
const checkUi = () => '';

async function run(argv, env = process.env, fetchImpl = globalThis.fetch) {
  const flags = new Set(argv.filter((a) => a.startsWith('--')));
  const langs = argv.filter((a) => !a.startsWith('--'));
  const deck = loadDeck();
  const store = readStore();

  if (flags.has('--rebuild')) { saveStore(store, deck); console.log('Rebuilt translations.js from translations.json'); return; }

  if (flags.has('--list')) {
    for (const lang of Object.keys(store).sort()) {
      const stale = deck.cards.filter((c) => !store[lang].cards || !store[lang].cards[c.slug] || store[lang].cards[c.slug]._src !== cardHash(c)).length;
      console.log(lang + ': ' + (deck.cards.length - stale) + '/' + deck.cards.length + ' current' + (stale ? ', ' + stale + ' stale or missing' : ''));
    }
    return;
  }

  if (!langs.length) {
    console.error('Usage: GEMINI_API_KEY=... node translate.js <lang> [<lang> ...] [--force]\n       node translate.js --rebuild | --list');
    process.exitCode = 1; return;
  }
  if (!env.GEMINI_API_KEY) { console.error('Set GEMINI_API_KEY in your environment first. Do not paste keys into source files.'); process.exitCode = 1; return; }

  for (const lang of langs) {
    if (!/^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$/.test(lang)) { console.error('Skipping "' + lang + '": not a language code like es or zh-CN'); continue; }
    store[lang] = store[lang] || { ui: null, cards: {} };
    store[lang].cards = store[lang].cards || {};
    console.log('\n== ' + lang + ' ==');
    try {
      if (flags.has('--force') || !store[lang].ui || store[lang].uiSrc !== uiHash(deck.ui)) {
        process.stdout.write('  ui ... ');
        store[lang].ui = await translateObject(lang, deck.ui, UI_FIELDS, checkUi, env, fetchImpl);
        store[lang].uiSrc = uiHash(deck.ui);
        saveStore(store, deck); console.log('ok');
      }
      for (const card of deck.cards) {
        const have = store[lang].cards[card.slug];
        if (!flags.has('--force') && have && have._src === cardHash(card)) { console.log('  ' + card.slug + ' ... up to date'); continue; }
        process.stdout.write('  ' + card.slug + ' ... ');
        const t = await translateObject(lang, card, FIELDS, checkCard, env, fetchImpl);
        store[lang].cards[card.slug] = Object.assign({}, t, { _src: cardHash(card) });
        saveStore(store, deck);
        console.log('ok');
        // Sleep between cards to respect rate limits
        await sleep(3000);
      }
    } catch (e) {
      console.error('\n  FAILED for ' + lang + ': ' + e.message);
      process.exitCode = 1;
      if (/HTTP (400|401|403|404)/.test(e.message)) break;
    }
  }
  saveStore(store, deck);
}

module.exports = { run, tagSig, cardHash, loadDeck };
if (require.main === module) run(process.argv.slice(2)).catch((e) => { console.error(e); process.exit(1); });
